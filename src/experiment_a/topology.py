"""
Topological invariants of majority tournaments.

This module implements the three orientation-related invariants used in
Experiment A. The unifying mathematical framing:

    Given a finite set A of n alternatives and a majority tournament T on A
    (an orientation of the complete graph K_n induced by pairwise majority
    preferences), we ask whether the pattern of Condorcet cycles on T is a
    "removable" local artefact or a genuine global topological obstruction.

    The natural 2-dimensional simplicial complex is K = 2-skeleton of the
    (n-1)-simplex: all vertices, all pairs as edges, all triples as filled
    triangles. The indicator of cyclic triangles is a 2-cochain c_T in
    C^2(K; F_2). Two facts:

      (a) c_T is the coboundary delta^1(phi) of some 1-cochain phi iff cycles
          can be eliminated by flipping the majority direction on a subset of
          edges specified by phi. When this happens, cyclicity is a purely
          local artefact of which edges point which way.

      (b) c_T represents a non-zero class in H^2(K; F_2) iff no such phi
          exists -- cycles cannot be removed by any edge flips, and there is
          a global obstruction to coherent orientation.

    H_2(K; F_2) is generated by the boundaries of 4-subsets (each 4-subset
    gives a copy of S^2 sitting inside K). By Poincare duality / explicit
    pairing, the class [c_T] is determined by its evaluations on these S^2
    generators. The evaluation on a 4-subset {a,b,c,d} equals the parity of
    the number of cyclic triangles among its four sub-triples {abc, abd,
    acd, bcd}. This gives the "tetrahedral parity" invariant.

    The complementary invariant is beta_1(F_2) of the "acyclic triangle
    complex" K_acyc(T), obtained from K by keeping only acyclic triples as
    2-simplices. Non-vanishing beta_1 records cycles in the 1-skeleton that
    are NOT boundaries of filled acyclic triangles -- i.e., the holes
    carved out by cyclic triples.

    Together, these invariants measure two complementary notions of
    obstruction: one cohomological ("can edge flips repair cycles?") and
    one homological ("how many holes do cycles punch in the complex?").
"""

from __future__ import annotations

from itertools import combinations
from typing import Dict, Tuple

import numpy as np


# ---------------------------------------------------------------------------
# Basic tournament predicates
# ---------------------------------------------------------------------------

def validate_tournament(T: np.ndarray) -> None:
    """Raise ValueError if T is not a well-defined tournament.

    A tournament is an orientation of K_n: T[i,j] + T[j,i] == 1 for all i != j,
    and T[i,i] == 0. Ties must be resolved by the caller before calling
    topology routines.
    """
    if T.ndim != 2 or T.shape[0] != T.shape[1]:
        raise ValueError(f"T must be square; got shape {T.shape}")
    n = T.shape[0]
    if not np.all(np.diag(T) == 0):
        raise ValueError("T must have zero diagonal")
    off = T + T.T
    for i in range(n):
        off[i, i] = 1  # mask diagonal
    if not np.all(off == 1):
        bad = np.argwhere(off != 1)
        raise ValueError(
            f"T is not a tournament; T[i,j] + T[j,i] != 1 at, e.g., {tuple(bad[0])}"
        )


def is_cyclic_triple(T: np.ndarray, a: int, b: int, c: int) -> bool:
    """True iff {a,b,c} forms a directed 3-cycle under T."""
    # Two cyclic orientations: a->b->c->a and a->c->b->a.
    if T[a, b] and T[b, c] and T[c, a]:
        return True
    if T[a, c] and T[c, b] and T[b, a]:
        return True
    return False


# ---------------------------------------------------------------------------
# Invariant 1: Condorcet cycle count
# ---------------------------------------------------------------------------

def count_condorcet_cycles(T: np.ndarray) -> int:
    """Total number of cyclic 3-subsets in T."""
    n = T.shape[0]
    return sum(
        1 for (a, b, c) in combinations(range(n), 3) if is_cyclic_triple(T, a, b, c)
    )


# ---------------------------------------------------------------------------
# Invariant 2: tetrahedral parities (H^2 obstruction representative)
# ---------------------------------------------------------------------------

def tetrahedral_parities(T: np.ndarray) -> np.ndarray:
    """Parity of cyclic triples per 4-subset.

    For each 4-subset {a,b,c,d}, count how many of its four sub-triples are
    cyclic, and take that count mod 2.

    Returns
    -------
    np.ndarray of shape (C(n,4),), dtype int8, values in {0,1}.

    Interpretation
    --------------
    Entry for 4-subset S is the F_2 evaluation of the cyclic-triangle
    2-cochain on the 2-sphere bounding the tetrahedron on S. If ANY entry
    is 1, the cocycle [c_T] is non-zero in H^2(K; F_2) -- no edge-flipping
    assignment can remove all cycles.
    """
    n = T.shape[0]
    parities = []
    for (a, b, c, d) in combinations(range(n), 4):
        count = (
            int(is_cyclic_triple(T, a, b, c))
            + int(is_cyclic_triple(T, a, b, d))
            + int(is_cyclic_triple(T, a, c, d))
            + int(is_cyclic_triple(T, b, c, d))
        )
        parities.append(count & 1)
    return np.asarray(parities, dtype=np.int8)


def cohomology_class_nonzero(T: np.ndarray) -> bool:
    """Direct test: does the cyclic-triangle 2-cochain c_T lie in im(delta^1)?

    Equivalent to ``tetrahedral_parities(T).any()`` but computed via linear
    algebra over F_2. Included as an independent cross-check.
    """
    n = T.shape[0]
    edges = list(combinations(range(n), 2))
    edge_idx = {e: i for i, e in enumerate(edges)}
    triples = list(combinations(range(n), 3))

    num_edges = len(edges)
    num_triples = len(triples)

    # delta^1 : C^1 -> C^2 as a (num_triples x num_edges) matrix over F_2.
    delta_1 = np.zeros((num_triples, num_edges), dtype=np.int8)
    for i, (a, b, c) in enumerate(triples):
        for e in [(a, b), (a, c), (b, c)]:
            delta_1[i, edge_idx[e]] = 1

    c_T = np.zeros(num_triples, dtype=np.int8)
    for i, (a, b, c) in enumerate(triples):
        if is_cyclic_triple(T, a, b, c):
            c_T[i] = 1

    rank_delta_1 = _matrix_rank_f2(delta_1)
    augmented = np.concatenate([delta_1, c_T.reshape(-1, 1)], axis=1)
    rank_aug = _matrix_rank_f2(augmented)
    return rank_aug > rank_delta_1


# ---------------------------------------------------------------------------
# Invariant 3: beta_1 of the acyclic triangle complex
# ---------------------------------------------------------------------------

def betti_1_acyclic_complex(T: np.ndarray) -> Dict[str, int]:
    """Beta_1 (F_2) of the complex keeping only acyclic triples as 2-simplices.

    The 1-skeleton is K_n (connected), so dim ker(d_1) = |E| - n + 1.
    beta_1 = dim ker(d_1) - rank(d_2) over F_2.

    Returns
    -------
    dict with keys: beta_1, num_edges, num_acyclic_triples, num_total_triples.
    """
    n = T.shape[0]
    edges = list(combinations(range(n), 2))
    edge_idx = {e: i for i, e in enumerate(edges)}

    acyclic_triples = [
        (a, b, c)
        for (a, b, c) in combinations(range(n), 3)
        if not is_cyclic_triple(T, a, b, c)
    ]
    num_edges = len(edges)
    num_acyclic = len(acyclic_triples)
    num_total = n * (n - 1) * (n - 2) // 6

    if num_acyclic == 0:
        rank_d2 = 0
    else:
        d2 = np.zeros((num_edges, num_acyclic), dtype=np.int8)
        for j, (a, b, c) in enumerate(acyclic_triples):
            for e in [(a, b), (a, c), (b, c)]:
                d2[edge_idx[e], j] = 1
        rank_d2 = _matrix_rank_f2(d2)

    dim_ker_d1 = num_edges - n + 1  # K_n is connected for n >= 1
    beta_1 = dim_ker_d1 - rank_d2
    return {
        "beta_1": int(beta_1),
        "num_edges": int(num_edges),
        "num_acyclic_triples": int(num_acyclic),
        "num_total_triples": int(num_total),
    }


# ---------------------------------------------------------------------------
# Main entry point
# ---------------------------------------------------------------------------

def topological_invariants(T: np.ndarray) -> Dict[str, float]:
    """Compute all orientation-related invariants for tournament T."""
    validate_tournament(T)
    n = T.shape[0]
    total_triples = max(1, n * (n - 1) * (n - 2) // 6)
    total_4subsets = n * (n - 1) * (n - 2) * (n - 3) // 24

    c_cycles = count_condorcet_cycles(T)
    parities = tetrahedral_parities(T)
    b1 = betti_1_acyclic_complex(T)

    odd_frac = float(parities.mean()) if parities.size > 0 else 0.0
    return {
        "n": int(n),
        "condorcet_3cycles": int(c_cycles),
        "condorcet_3cycle_fraction": float(c_cycles) / total_triples,
        "num_4subsets": int(total_4subsets),
        "odd_parity_4subsets": int(parities.sum()),
        "odd_parity_fraction": odd_frac,
        "cohomology_class_nonzero": bool(parities.any()),
        "beta_1_acyclic_complex": int(b1["beta_1"]),
        "num_acyclic_triples": int(b1["num_acyclic_triples"]),
    }


# ---------------------------------------------------------------------------
# F_2 linear algebra
# ---------------------------------------------------------------------------

def _matrix_rank_f2(M: np.ndarray) -> int:
    """Rank over F_2 via Gaussian elimination.

    In-place on a copy; O(rows * cols * min(rows, cols)) time, which is fine
    for the tournament sizes we use (n <= ~30, so matrices are at most a few
    thousand entries).
    """
    if M.size == 0:
        return 0
    A = (np.asarray(M, dtype=np.int8) & 1).copy()
    rows, cols = A.shape
    rank = 0
    pivot_row = 0
    for col in range(cols):
        if pivot_row >= rows:
            break
        # Find a pivot in this column at or below the current pivot row.
        sub = A[pivot_row:, col]
        nz = np.flatnonzero(sub)
        if nz.size == 0:
            continue
        swap = pivot_row + int(nz[0])
        if swap != pivot_row:
            A[[pivot_row, swap]] = A[[swap, pivot_row]]
        # Eliminate this column from every other row.
        for r in range(rows):
            if r != pivot_row and A[r, col]:
                A[r] ^= A[pivot_row]
        rank += 1
        pivot_row += 1
    return rank
